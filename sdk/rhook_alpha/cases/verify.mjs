// Recorded proof/receipt verification, with no EVM re-execution.
import assert from 'node:assert/strict';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {readBoundedJson,readRawJournal} from './io.mjs';
import {canonical} from '../../engine/adapters/hookr-case/primitives.mjs';
import {authenticatePackage,verifyPair} from './adapters/hookr.mjs';
const sha = raw => createHash('sha256').update(raw).digest('hex');
const root=path.resolve(process.argv[2]);
const read=(name,max=32<<20,fraction=false)=>readBoundedJson(path.join(root,name),max,fraction);
const capsule=read('inputs/CAPSULE.json',65536);
const doc=read('inputs/PLAN.json',65536);
const binding=read('BINDING.json',65536).value;
const c=capsule.value,p=doc.value;
const capBody={...c};delete capBody.capsuleId;
assert.equal(c.capsuleId,sha(Buffer.from('rhook/case-capsule/0.1\n'+canonical(capBody))));
assert.equal(p.capsuleId,c.capsuleId);assert.equal(p.caseId,c.caseId);
assert.equal(c.adapter.id,'hookr-1.lp-bps/1');
assert.equal(c.execution.profile,'nitro-hookr-lp/0.1');
assert.equal(c.execution.inputCommitment,p.runtimePlan.inputCommitment);
assert.equal(c.execution.witnessCommitment,p.runtimePlan.witnessCommitment);
assert.deepEqual(c.arrivals,p.runtimePlan.arrivals);
assert.deepEqual(c.checkpoint,p.runtimePlan.checkpoint);
for(const [k,v] of Object.entries(c.target))assert.deepEqual(p.runtimePlan[k],v);
assert.equal(binding.outputPath,root);assert.equal(binding.capsuleId,c.capsuleId);
assert.equal(binding.trustedCheckpoint,c.checkpoint.blockHash);
assert.equal(binding.capsuleSha256,sha(capsule.raw));assert.equal(binding.planSha256,sha(doc.raw));
const b={...binding};delete b.operationCommitment;
assert.equal(binding.operationCommitment,sha(Buffer.from('rhook/case-operation/0.1\n'+canonical(b))));
assert.deepEqual(binding.maximumInvocations,{ACTUAL:1,BRANCH:1,B:0});assert.equal(binding.RPC,0);assert.equal(binding.WSS,0);
const a=read('runtime/AUTHORITY.json',65536),start=read('runtime/STARTED.json',4096).value;
assert.deepEqual(a.value.binding,binding);
assert.equal(start.authoritySha256,sha(a.raw));assert.equal(start.operationCommitment,binding.operationCommitment);
const began=Date.parse(start.utc)/1000;
assert(Number.isInteger(a.value.notBeforeUnix)&&Number.isInteger(a.value.expiresUnix));
assert(began>=a.value.notBeforeUnix&&began<a.value.expiresUnix&&a.value.expiresUnix-a.value.notBeforeUnix<=600);
const native=read('runtime/NATIVE_COMPLETION.json').value;
assert.equal(native.operationCommitment,binding.operationCommitment);
assert.equal(native.result.terminal,'GO_HOOKR_PAIR_OBSERVED_UNQUALIFIED');
assert.equal(native.result.canonicalActualValid,true);
assert.deepEqual(native.result.nativeInvocations,{ACTUAL:1,BRANCH:1,B:0});
const rows=readRawJournal(path.join(root,'runtime/JOURNAL.jsonl'));
assert.deepEqual(rows.map(x=>x.event),['ACTUAL_ENTERED','CANONICAL_ACTUAL_MATCH','BRANCH_ENTERED','PAIR_OBSERVED_UNQUALIFIED']);
assert.deepEqual(rows[0].data,{ACTUAL:1,BRANCH:0,B:0});assert.deepEqual(rows[2].data,{ACTUAL:1,BRANCH:1,B:0});
assert.deepEqual(rows[3].data,native.result);
const resource=read('runtime/PROCESS_COMPLETION.json',65536,true).value;
assert.equal(resource.workerReaped,true);assert.equal(resource.exitCode,0);assert.equal(resource.stop,null);assert.equal(resource.resourcesReliable,true);
assert(resource.wallSeconds<=120&&resource.workerAndObserverCpuSeconds<=120&&resource.sampledPeakWorkerRSS<=1073741824);
const raw=read('inputs/BLOCK_PACKAGE.json',8<<20).raw;
assert.equal(sha(raw),binding.packageSha256);
const pkg=await authenticatePackage(raw,p.runtimePlan);
const verified=verifyPair(read('runtime/ACTUAL.json').value,read('runtime/BRANCH.json').value,p.runtimePlan,pkg);
console.log(JSON.stringify({...verified,chainTrust:'OPERATOR_PINNED_CHECKPOINT',capsuleId:c.capsuleId,operationCommitment:binding.operationCommitment}));
